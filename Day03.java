public class EscapeSequence {
    public static void main(String[] args) {
        System.out.println("Nama:\tAfdal");
        System.out.println("Halo\nDunia");
        System.out.println("Dia berkata: \"Saya belajar Java\"");
        System.out.println("Saya suka \'Java\'");
        System.out.println("Lokasi file: C:\\Java");
    }
}
